// Demo persistence in localStorage only. No backend, no real dispatch.
import { DEMO_INCIDENTS, DEMO_POLICE_UNITS, DEMO_AMBULANCE_UNITS, DEMO_FIRE_UNITS, DemoIncident, DemoUnit } from './demoData';
const INC_KEY = 'aegis_demo_incidents';
const ACT_KEY = 'aegis_demo_activity';
export function loadDemoIncidents(): DemoIncident[] {
  try { const raw = localStorage.getItem(INC_KEY); if (raw) { const v = JSON.parse(raw); if (Array.isArray(v) && v.length) return v; } } catch { /* ignore */ }
  return [...DEMO_INCIDENTS];
}
export function saveDemoIncidents(list: DemoIncident[]) { try { localStorage.setItem(INC_KEY, JSON.stringify(list)); } catch { /* ignore */ } }
export function loadDemoActivity(): string[] {
  try { const raw = localStorage.getItem(ACT_KEY); if (raw) return JSON.parse(raw); } catch { /* ignore */ }
  return ['Demo simulation started — dashboard is using demo data.', 'Demo incident DEMO-1001 logged in simulation.'];
}
export function saveDemoActivity(list: string[]) { try { localStorage.setItem(ACT_KEY, JSON.stringify(list.slice(0, 30))); } catch { /* ignore */ } }
export function demoStats(incidents: DemoIncident[], units: DemoUnit[]) {
  const total = incidents.length;
  const active = incidents.filter((i) => i.status !== 'RESOLVED').length;
  const resolved = incidents.filter((i) => i.status === 'RESOLVED').length;
  const available = units.filter((u) => u.status === 'AVAILABLE').length;
  return { total, active, resolved, available, totalUnits: units.length };
}
export function allDemoUnits(): DemoUnit[] { return [...DEMO_POLICE_UNITS, ...DEMO_AMBULANCE_UNITS, ...DEMO_FIRE_UNITS]; }
const TITLES: Array<[string, string, DemoIncident['priority']]> = [
  ['Fire in a shop', 'FIRE_INCIDENT', 'HIGH'], ['Road accident reported', 'ROAD_ACCIDENT', 'HIGH'],
  ['Medical help requested', 'MEDICAL_EMERGENCY', 'CRITICAL'], ['Water supply complaint', 'WATER_SUPPLY', 'MEDIUM'],
  ['Power outage reported', 'POWER_OUTAGE', 'MEDIUM'], ['Flooding in a low area', 'FLOOD', 'HIGH'],
];
const CITIES = ['Bengaluru', 'Hyderabad', 'Raichur', 'Kalaburagi', 'Hubballi', 'Mysuru'];
export function randomDemoIncident(nextId: number): DemoIncident {
  const [title, category, priority] = TITLES[Math.floor(Math.random() * TITLES.length)];
  const city = CITIES[Math.floor(Math.random() * CITIES.length)];
  return { id: `DEMO-${nextId}`, title, category, priority, status: 'ACTIVE', city, address: `Demo location, ${city}`, description: 'Simulated incident generated by demo simulation.', createdAt: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }) };
}
